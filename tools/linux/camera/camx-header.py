"""Generate the imx351 driver's register header from camx-regs.py output (camera step 4, docs/research/33 "CAMERA").
The OUTPUT holds register data derived from the phone's own proprietary camx module: generate it locally at build
time (build-imx351.sh), never commit it. Emits struct cci_reg_sequence arrays (v4l2-cci) for <init> and <mode>.
usage: python3 -I camx-header.py <tables.txt> <init-table-offset> <mode-table-offset> <out.h>"""
import sys
t = {}; cur = None
for ln in open(sys.argv[1]):
    if ln.startswith('# table at'): cur = ln.split()[3].rstrip(':'); continue
    if ln.startswith('#') or cur is None: continue
    t[cur] = [(int(x.split('=')[0], 16), int(x.split('=')[1].split('+')[0], 16)) for x in ln.split()]
o = ['/* GENERATED by tools/linux/camera/camx-header.py from the phone\'s own camx sensor module - do not commit */', '']
for name, off in (('imx351_init_regs', sys.argv[2]), ('imx351_mode_regs', sys.argv[3])):
    o.append('static const struct cci_reg_sequence %s[] = {	/* table %s */' % (name, off))
    o += ['\t{ CCI_REG8(0x%04x), 0x%02x },' % (a, v) for a, v in t[off] if a != 0x0100]	# stream on/off is the driver's
    o.append('};'); o.append('')
open(sys.argv[4], 'w', newline='\n').write('\n'.join(o)); print('wrote', sys.argv[4], len(o), 'lines')
